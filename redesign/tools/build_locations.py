"""Build assets/data/locations.js from the site's public WP Store Locator data (research/raw-crawl/store-locator.json)
plus the homepage blurbs. Usage: python3 -I tools/build_locations.py"""
import html, json, os, re
ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
raw = json.load(open(os.path.join(ROOT, 'research/raw-crawl/store-locator.json'), encoding='utf-8'))
SKIP = {'Kent Newton Salon', 'ISBCC'}  # not hospitality venues; confirm with client
FIX = {'Braodway': 'Broadway', 'Stret': 'Street', 'Merrimak': 'Merrimack', 'Brigthon': 'Brighton', 'S. Boston': 'South Boston',
       'S. Portland': 'South Portland', 'Westboro': 'Westborough'}
TYPE_RULES = [
    ('pastry', r'pastry|patisserie|bake|bakery|ice and dough|dolce vita'),
    ('cafe', r'caff[eé]|cafe|fupo|palazzo|b\. sisters|34 park|leon and company'),
    ('market', r'market|deli|food inc|pace and son|terra cotta pasta|casa d.italia|polcari'),
    ('restaurant', r'.'),
]
BLURBS = {  # from the current homepage
    'Taberna De Haro': 'Spanish taberna; espresso after dinner', 'BOSA Coastal Italian': 'Creative coastal Italian cuisine',
    'Pazza on Porter': '"Crazy" good food in East Boston', 'The Wellington': 'Dinner and a decaf latte',
    'Caffe Dello Sport Eastie': 'A taste of the North End in Eastie', 'Lakon Paris Patisserie': 'A pastry with your espresso',
    'La Dolce Vita': 'Cappuccino and dessert', "Broadway's Pastry and Coffee": 'A pastry with your cappuccino',
    'El Potro': 'Newest locations pouring Guglielmo', 'Forcella': 'Newest locations pouring Guglielmo', 'Nando': 'Newest locations pouring Guglielmo',
}
STATE = {'Massachusetts': 'MA', 'MA': 'MA', 'Maine': 'ME'}
def fix(s):
    s = html.unescape(re.sub(r'<[^>]+>', '', s or '')).strip()
    for a, b in FIX.items(): s = re.sub(r'\b' + re.escape(a) + r'\b', b, s)
    return re.sub(r'\s+', ' ', s)
venues = []
for x in raw:
    name = fix(x['store'])
    if name in SKIP: continue
    city = fix(x['city']).replace('Roxbury', 'Roxbury')
    addr = fix(x['address']).replace(' Somerville, MA 02145', '')
    st = STATE.get(fix(x['state']), 'MA' if not x['state'] else fix(x['state']))
    t = next(k for k, rx in TYPE_RULES if re.search(rx, name, re.I))
    hood = 'North End' if (city == 'Boston' and float(x['lat']) > 42.361 and float(x['lng']) > -71.0575) else None
    v = dict(name=name, type=t, address=addr, city=city, state=st, zip=fix(x['zip']), lat=float(x['lat']), lng=float(x['lng']))
    if hood: v['neighborhood'] = hood
    if x.get('phone'): v['phone'] = fix(x['phone'])
    if x.get('url'): v['url'] = fix(x['url']).replace('http://', 'https://')
    if name in BLURBS: v['blurb'] = BLURBS[name]
    venues.append(v)
data = {
  'source': 'lespressousa.com WP Store Locator (public), fetched 2026-10-12; 2 non-hospitality entries excluded; obvious typos corrected; types inferred from names.',
  'venues': venues,
  'distributors': [
    {'name': "Guglielmo USA (L'Espresso USA)", 'region': 'New England (HQ)', 'contact': 'Domenico Elia', 'phone': '(617) 612-0090', 'email': 'info@lespressousa.com', 'city': 'Greater Boston', 'state': 'MA', 'lat': 42.36, 'lng': -71.06},
    {'name': 'Espresso World', 'region': 'Illinois', 'contact': 'Husso Klebic', 'phone': '(773) 275-8309', 'email': 'espressoworld@hotmail.com', 'city': 'Chicago', 'state': 'IL', 'lat': 41.95, 'lng': -87.70},
    {'name': 'Moka & Company', 'region': 'Pennsylvania', 'contact': 'Joe Sgro', 'phone': '(717) 393-9666', 'email': 'joe.sgro@prodigy.net', 'city': 'Lancaster', 'state': 'PA', 'lat': 40.04, 'lng': -76.31},
  ],
  'company': {'name': 'Guglielmo USA', 'legal': "L'Espresso USA", 'founded': 2000, 'founder': 'Mimmo (Domenico) Elia', 'phone': '(617) 612-0090', 'phone2': '(617) 612-1227', 'email': 'info@lespressousa.com', 'region': 'Greater Boston, Massachusetts', 'canada_since': 2003},
}
open(os.path.join(ROOT, 'assets/data/locations.js'), 'w', encoding='utf-8').write(
  '/* Venues serving Guglielmo: the public store-locator data on lespressousa.com (78 entries, 2 excluded), cleaned.\n   Generated by tools/build_locations.py. Types are inferred from venue names; confirm with the client. */\nwindow.GUSA_LOCATIONS = ' + json.dumps(data, ensure_ascii=False, indent=1) + ';\n')
from collections import Counter
print(len(venues), Counter(v['type'] for v in venues), Counter(v['city'] for v in venues).most_common(8), sum(1 for v in venues if v.get('neighborhood')), 'in North End')
