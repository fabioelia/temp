#!/usr/bin/env python3
"""Weekly retrospective facts for the AI Trading Challenge.

    python3 trading-experiment/review.py week --end 2026-10-23 [--start 2026-10-19] [--out trading-experiment/reviews/2026-W43.md]

    python3 trading-experiment/review.py snapshot --date 2026-10-23     # fresh numbers for an agent brief

Prints (or writes) the measurable half of the weekly review: real and paper results against SPY, every
round trip with its best and worst daily mark while open (MFE/MAE) and its value if held to the week's end,
the gap between real and paper fills, what happened to every proposal, failed gate tickets, fees and taxes.
The judgement half (why it went well or badly, what to change) is written on top of it by the Sunday run;
see DAILY_ROUTINE.md "Weekly retrospective".
"""
import argparse
import sys
from datetime import date, timedelta
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import tracker as T  # noqa: E402
import quotes as Q  # noqa: E402

DATA = T.DATA
LIVE_LEDGER, TICKETS, PRICES = DATA / "live_ledger.csv", DATA / "live_tickets.csv", DATA / "prices"


def round_trips(fills):
    """Average-cost round trips from fills ({date, side, ticker, qty, price, fees}, price per share)."""
    pos, trips = {}, []
    for r in sorted(fills, key=lambda r: (r["date"], 0 if r["side"] == "buy" else 1)):
        t, q, px, f = r["ticker"], float(r["qty"]), float(r["price"]), float(r["fees"] or 0)
        m = T.mult(t)
        p = pos.setdefault(t, {"qty": 0.0, "cost": 0.0, "opened": r["date"]})
        if r["side"] == "buy":
            if p["qty"] <= 1e-9:
                p["opened"] = r["date"]
            p["qty"] += q
            p["cost"] += q * px * m + f
        else:
            avg = p["cost"] / p["qty"]
            pl = (q * px * m - f) - avg * q
            trips.append({"ticker": t, "opened": p["opened"], "closed": r["date"], "qty": q,
                          "entry": avg / m, "exit": px, "pl": pl, "ret": pl / (avg * q)})
            p["cost"] -= avg * q
            p["qty"] -= q
    open_pos = {t: p for t, p in pos.items() if p["qty"] > 1e-9}
    return trips, open_pos


def marks(ticker, start, end):
    """Daily closing marks (option mid or verified close) for ticker between start and end, from data/prices."""
    out = []
    for f in sorted(PRICES.glob("*.csv")):
        d = f.stem
        if start <= d <= end:
            for r in T.read_csv(f):
                if r["ticker"] == ticker and r["close"]:
                    out.append((d, float(r["close"])))
    return out


def last_mark(ticker, end):
    ms = marks(ticker, "0000-00-00", end)
    return ms[-1] if ms else (None, None)


def num(x):
    return f"{x:.3f}".rstrip("0").rstrip(".") if abs(x - round(x, 2)) > 1e-9 else f"{x:.2f}"


def money(x):
    return f"-${abs(x):,.2f}" if x < 0 else f"${x:,.2f}"


def pct(x):
    return f"{x * 100:+.1f}%"


# ---------------------------------------------------------------- snapshot (fresh numbers for every brief)
WATCH = ["SPY", "QQQ", "IWM", "TLT", "USO", "XLE", "MSFT", "NVDA", "META", "AAPL", "AMZN", "GOOGL"]
YAHOO_ONLY = [("^VIX", "VIX"), ("^VIX9D", "VIX9D"), ("^VIX3M", "VIX3M"), ("^TNX", "10y yield x10 (^TNX)"), ("CL=F", "WTI front month (CL=F)")]
MONTHS = "FGHJKMNQUVXZ"


def prev_trading_day(day):
    d = date.fromisoformat(day) - timedelta(days=1)
    while not T.is_trading_day(d):
        d -= timedelta(days=1)
    return d.isoformat()


def brent_contracts(day):
    """The two nearest Brent contracts on `day`: a contract stops trading at the end of the second month before delivery,
    so in October the nearest are December and January. Yahoo's BZ=F rolls to the later one early; name both."""
    d = date.fromisoformat(day)
    out = []
    for k in (2, 3):
        idx = d.month - 1 + k
        y, m = d.year + idx // 12, idx % 12 + 1
        out.append((f"BZ{MONTHS[m - 1]}{y % 100:02d}.NYM", f"Brent {date(y, m, 1):%b %Y}"))
    return out


def yahoo_close(sym, day):
    try:
        return Q.yahoo_daily(sym, day)["price"]
    except Exception:  # noqa: BLE001 - a missing series is reported as n/a
        return None


def snapshot(day, tickers=None):
    tickers = tickers or WATCH
    prev = prev_trading_day(day)
    # Cboe serves only the latest session, so the prior close is often Yahoo alone: accept it, labelled
    now, before = Q.closes(day, tickers), Q.closes(prev, tickers, allow_single=True)
    L = [f"## Market snapshot for {day} (generated by review.py snapshot; verified closes vs {prev})", "",
         "| Series | Close | Prior | Change | Source |", "|---|---|---|---|---|"]
    for t in tickers:
        a, b = now[t], before[t]
        if a["status"] == "ok" and b["status"] == "ok":
            L.append(f"| {t} | {a['price']:.2f} | {b['price']:.2f} | {pct(a['price'] / b['price'] - 1)} | {a['source']} |")
        else:
            L.append(f"| {t} | n/a | n/a | | no verified close (today {a['status']}, prior {b['status']}) |")
    brent = brent_contracts(day)
    for sym, label in YAHOO_ONLY + brent:
        a, b = yahoo_close(sym, day), yahoo_close(sym, prev)
        if a and b:
            L.append(f"| {label} | {a:.2f} | {b:.2f} | {pct(a / b - 1)} | Yahoo {sym}, single source |")
        else:
            L.append(f"| {label} | n/a | | | Yahoo {sym}: no close for {day} |")
    bz = yahoo_close("BZ=F", day)
    if bz:
        prices = [(label, yahoo_close(sym, day)) for sym, label in brent]
        match = min((x for x in prices if x[1]), key=lambda x: abs(x[1] - bz), default=None)
        L.append("")
        L.append(f"Yahoo's BZ=F closed {bz:.2f}, which is the {match[0]} contract." if match else f"Yahoo's BZ=F closed {bz:.2f}.")
    L += ["", "Any trigger on oil or rates must name one of these series exactly. Numbers in a brief come from this table, never from an older brief."]
    return "\n".join(L) + "\n"


# ---------------------------------------------------------------- ideas shadow book
IDEA_COLS = ["date", "persona", "contract", "ref_ask", "ref_source", "trigger", "confidence"]


def ideas(start, end):
    """Every idea logged in research/*/ideas-*.csv dated from the weekend before `start` through `end`
    (Sunday's proposals are for the week)."""
    lo = (date.fromisoformat(start) - timedelta(days=2)).isoformat()
    out = []
    for f in sorted((T.ROOT / "research").glob("*/ideas-*.csv")):
        out += [r for r in T.read_csv(f) if lo <= r["date"] <= end]
    return sorted(out, key=lambda r: (r["date"], r["persona"]))


def mark_now(contract):
    """Current mark: Cboe mid for an option (delayed), else the latest verified close we have."""
    if T.is_option(contract):
        try:
            q = Q.option_quote(contract)
            return round((q["bid"] + q["ask"]) / 2, 3), "Cboe mid (delayed) at review time"
        except Exception:  # noqa: BLE001
            return None, "no quote"
    d, px = last_mark(contract, "9999-12-31")
    return px, f"close {d}" if px else "no close"


def ideas_section(start, end, live_rows):
    rows = ideas(start, end)
    taken = {r["ticker"] for r in live_rows if r["side"] == "buy"}
    L = ["", "### Ideas shadow book (every persona's proposal, marked now)", ""]
    if not rows:
        return L + ["- No ideas logged (research/<date>/ideas-<persona>.csv)."]
    L += ["| Date | Persona | Contract | Ref ask | Mark now | Change | Taken | Confidence |", "|---|---|---|---|---|---|---|---|"]
    for r in rows:
        ref = float(r["ref_ask"]) if r.get("ref_ask") else None
        m, src = mark_now(r["contract"])
        chg = pct(m / ref - 1) if (m and ref) else "n/a"
        L.append(f"| {r['date']} | {r['persona']} | {r['contract']} | {r.get('ref_ask', '')} | {m if m is not None else 'n/a'} | {chg} | "
                 f"{'yes' if r['contract'] in taken else 'no'} | {r.get('confidence', '')} |")
    L.append("")
    L.append("Marks are taken when the review runs; a Sunday run sees Friday's close. Ref ask is the price the persona quoted, not a fill.")
    return L


def week_facts(start, end):
    L = [f"## Facts, week {start} to {end} (generated by review.py; numbers only)", ""]
    # equity
    eq = [r for r in T.read_csv(T.DATA / "equity.csv") if r["date"] <= end]
    before = [r for r in eq if r["date"] < start]
    wk = [r for r in eq if start <= r["date"] <= end]
    if wk:
        e0 = float(before[-1]["equity"]) if before else T.CFG["starting_cash"]
        e1 = float(wk[-1]["equity"])
        b0 = float(before[-1]["bench_value"]) if before and before[-1]["bench_value"] else T.CFG["starting_cash"]
        b1 = float(wk[-1]["bench_value"]) if wk[-1]["bench_value"] else None
        L.append(f"- Paper equity {money(e0)} -> {money(e1)} ({pct(e1 / e0 - 1)}); SPY buy-and-hold "
                 + (f"{money(b0)} -> {money(b1)} ({pct(b1 / b0 - 1)})" if b1 else "n/a"))
        lo = min(wk, key=lambda r: float(r["equity"]))
        hi = max(wk, key=lambda r: float(r["equity"]))
        L.append(f"- Paper closing high {money(float(hi['equity']))} ({hi['date']}), low {money(float(lo['equity']))} ({lo['date']})")
    live = [r for r in T.read_csv(LIVE_LEDGER) if r["date"] <= end]
    lfills = [{"date": r["date"], "side": r["side"], "ticker": r["ticker"], "qty": r["qty"], "price": r["avg_price"],
               "fees": r["fees"]} for r in live]
    ltrips, lopen = round_trips(lfills)
    realized = sum(t["pl"] for t in ltrips)
    open_val = sum(p["qty"] * (last_mark(t, end)[1] or 0) * T.mult(t) for t, p in lopen.items())
    open_cost = sum(p["cost"] for p in lopen.values())
    cap = T.CFG["live"]["capital_cap_usd"] if "live" in T.CFG else T.CFG["starting_cash"]
    L.append(f"- Real (live ledger): realized {money(realized)} to date; open positions cost {money(open_cost)}, "
             f"marked {money(open_val)}; experiment equity about {money(cap + realized - open_cost + open_val)}")
    # round trips
    pfills = [{"date": r["date"], "side": r["side"], "ticker": r["ticker"], "qty": r["qty"], "price": r["fill_price"],
               "fees": r["fees"]} for r in T.read_csv(T.LEDGER) if r["date"] <= end]
    ptrips, popen = round_trips(pfills)
    L += ["", "### Round trips closed this week", "",
          "| Book | Contract | Opened | Closed | Qty | Entry | Exit | P/L | Return | Best close (MFE) | Worst close (MAE) | If held to week end |",
          "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    n = 0
    for book, trips in (("real", ltrips), ("paper", ptrips)):
        for t in trips:
            if not (start <= t["closed"] <= end):
                continue
            n += 1
            # closing marks while the position was open: from the entry day to the day before the exit (the exit
            # day's close comes after a pre-close exit), plus the exit price itself
            ms = [x for x in marks(t["ticker"], t["opened"], t["closed"]) if x[0] < t["closed"]] + [(t["closed"], t["exit"])]
            best = max(ms, key=lambda x: x[1]) if ms else None
            worst = min(ms, key=lambda x: x[1]) if ms else None
            d_end, px_end = last_mark(t["ticker"], end)
            if (d_end or "") < end and T.is_option(t["ticker"]):
                # our own marks stop when the position closes; use the current quote (a Sunday review sees Friday's close)
                px_now, _ = mark_now(t["ticker"])
                px_end = px_now if px_now is not None else px_end
            held = f"{num(px_end)} ({pct(px_end / t['entry'] - 1)})" if px_end else "n/a"
            L.append(f"| {book} | {t['ticker']} | {t['opened']} | {t['closed']} | {t['qty']:g} | {t['entry']:.2f} | {t['exit']:.2f} | "
                     f"{money(t['pl'])} | {pct(t['ret'])} | "
                     + (f"{num(best[1])} {best[0]} ({pct(best[1] / t['entry'] - 1)})" if best else "n/a") + " | "
                     + (f"{num(worst[1])} {worst[0]} ({pct(worst[1] / t['entry'] - 1)})" if worst else "n/a") + f" | {held} |")
    if not n:
        L.append("| - | none | | | | | | | | | | |")
    L.append("")
    L.append("MFE/MAE use daily closing marks from the entry day to the day before the exit, plus the exit price; intraday peaks "
             "(for example a pre-close bid) are in journal.md.")
    # open at week end
    L += ["", "### Open at week end", ""]
    if lopen or popen:
        for book, op in (("real", lopen), ("paper", popen)):
            for t, p in op.items():
                d, px = last_mark(t, end)
                L.append(f"- {book}: {p['qty']:g} x {t}, cost {money(p['cost'])}, last mark {px} ({d})")
    else:
        L.append("- Flat in both books.")
    # execution gap real vs paper
    L += ["", "### Real versus paper fills", ""]
    pl = {(r["order_id"], r["side"]): r for r in T.read_csv(T.LEDGER)}
    gaps = 0
    for r in live:
        if not (start <= r["date"] <= end):
            continue
        p = pl.get((r["order_id"], r["side"]))
        if p:
            g = (float(r["avg_price"]) - float(p["fill_price"])) * (1 if r["side"] == "buy" else -1) * float(r["qty"]) * T.mult(r["ticker"])
            gaps += g
            L.append(f"- {r['date']} {r['side']} {r['ticker']}: real {r['avg_price']} vs paper {p['fill_price']} -> real cost {money(g)} worse"
                     if g >= 0 else f"- {r['date']} {r['side']} {r['ticker']}: real {r['avg_price']} vs paper {p['fill_price']} -> real {money(-g)} better")
    L.append(f"- Net execution gap this week: {money(gaps)} (positive = the real account did worse than the paper model)")
    # orders
    orders = [o for o in T.read_csv(T.ORDERS)
              if start <= o["created"] <= end or start <= (o.get("confirmed_on") or "") <= end or start <= o["gtd"] <= end]
    L += ["", "### Proposals and decisions", "",
          f"- Orders decided this week (created, confirmed or due): {len(orders)}; filled {sum(o['status'] == 'filled' for o in orders)}, "
          f"cancelled {sum(o['status'] == 'cancelled' for o in orders)}, still pending {sum(o['status'] == 'pending' for o in orders)}, "
          f"expired unconfirmed {sum(o['status'] == 'expired' for o in orders)}"]
    for o in orders:
        why = o.get("reason") or ""
        L.append(f"- {o['id']} {o['created']} {o['side']} {o['ticker']}: {o['status']}"
                 + (f" (confirmed {o['confirmed_on']})" if o.get("confirmed_on") else "") + (f"; {why[:160]}" if why else ""))
    tickets = [t for t in T.read_csv(TICKETS) if start <= t["date"] <= end]
    if tickets:
        L += ["", "### Real-money gate tickets", ""]
        for t in tickets:
            L.append(f"- {t['ticket']} {t['date']} {t['side']} {t['ticker']} {t['status']}" + (f": {t['reason'][:160]}" if t["reason"] else ""))
    # costs and taxes
    pf = sum(float(r["fees"]) for r in T.read_csv(T.LEDGER) if start <= r["date"] <= end)
    lf = sum(float(r["fees"]) for r in live if start <= r["date"] <= end)
    tx = T.tax_memo(lfills)
    L += ["", "### Costs and taxes", "",
          f"- Fees this week: real {money(lf)}, paper {money(pf)}",
          f"- Real-fill tax memo, year to date: short-term {money(tx['short_term'])}; possible wash sales {len(tx['wash'])}"]
    # research coverage
    days = []
    d = date.fromisoformat(start)
    while d.isoformat() <= end:
        folder = T.ROOT / "research" / d.isoformat()
        if folder.exists():
            days.append(f"{d.isoformat()}: {', '.join(sorted(p.stem for p in folder.glob('*.md')))}")
        d += timedelta(days=1)
    L += ["", "### Research memos on file", ""] + [f"- {x}" for x in days] if days else []
    L += ideas_section(start, end, live)
    return "\n".join(L) + "\n"


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = p.add_subparsers(dest="cmd", required=True)
    w = sub.add_parser("week")
    w.add_argument("--end", required=True, help="last day of the week (YYYY-MM-DD)")
    w.add_argument("--start", help="first day; default the Monday of --end's week")
    w.add_argument("--out", help="write to this file instead of stdout")
    w.add_argument("--force", action="store_true", help="overwrite --out even if it already exists (it may hold the written analysis)")
    sn = sub.add_parser("snapshot")
    sn.add_argument("--date", required=True)
    sn.add_argument("--tickers", help="comma-separated; default the watchlist")
    a = p.parse_args()
    if a.cmd == "snapshot":
        print(snapshot(a.date, [t.strip().upper() for t in a.tickers.split(",")] if a.tickers else None))
        return
    end = date.fromisoformat(a.end)
    start = a.start or (end - timedelta(days=end.weekday())).isoformat()
    text = week_facts(start, end.isoformat())
    if a.out:
        if Path(a.out).exists() and not a.force:
            sys.exit(f"{a.out} exists (it may already hold the analysis); print to stdout instead, or pass --force")
        Path(a.out).parent.mkdir(parents=True, exist_ok=True)
        Path(a.out).write_text(text)
        print(f"wrote {a.out}")
    else:
        print(text)


if __name__ == "__main__":
    main()
